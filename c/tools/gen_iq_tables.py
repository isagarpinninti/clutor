#!/usr/bin/env python3
"""Writes c/src/iq_tables.h from ggml's ggml-common.h (the lookup tables of the IQ quantization types).

    gen_iq_tables.py PATH/TO/ggml-common.h > c/src/iq_tables.h

The tables are data that the IQ formats are defined by: a file quantized with them can only be read with the same numbers. ggml is MIT licensed.
"""
import re, sys

src = open(sys.argv[1], encoding="utf-8").read()
want = {"ksigns_iq2xs": "uint8_t", "ksigns64": "uint64_t", "iq2xxs_grid": "uint64_t", "iq2xs_grid": "uint64_t", "iq2s_grid": "uint64_t", "iq3xxs_grid": "uint32_t", "iq3s_grid": "uint32_t", "iq1s_grid": "uint64_t"}
out = ["/* Lookup tables of the IQ quantization types, taken from ggml (https://github.com/ggml-org/ggml, ggml-common.h), which is MIT licensed:",
       " * Copyright (c) 2023-2024 The ggml authors. Generated by tools/gen_iq_tables.py; do not edit. */",
       "#ifndef CL_IQ_TABLES_H", "#define CL_IQ_TABLES_H", "#include <stdint.h>", ""]
for name, ctype in want.items():
    m = re.search(r"GGML_TABLE_BEGIN\(%s, %s, ([A-Za-z0-9_]+)\)(.*?)GGML_TABLE_END\(\)" % (ctype, name), src, re.S)
    if not m:
        sys.exit("table not found: " + name)
    size = {"NGRID_IQ1S": 2048}.get(m.group(1)) or int(m.group(1))
    vals = [v for v in re.findall(r"0x[0-9a-fA-F]+|\d+", m.group(2))]
    if len(vals) != size:
        sys.exit("%s: expected %d values, found %d" % (name, size, len(vals)))
    suffix = "ull" if ctype == "uint64_t" else ""
    per = 4 if ctype == "uint64_t" else 8 if ctype == "uint32_t" else 16
    out.append("static const %s %s[%d] = {" % (ctype, name, size))
    for i in range(0, size, per):
        out.append("  " + ", ".join(v + suffix for v in vals[i:i + per]) + ",")
    out.append("};")
# the sign byte spread to eight bytes (0xff where a bit is set), for the formats that store signs as a byte
out.append("static const uint64_t smask64[256] = {")
for i in range(0, 256, 4):
    out.append("  " + ", ".join("0x%016xull" % sum(0xff << (8 * j) for j in range(8) if (v >> j) & 1) for v in range(i, i + 4)) + ",")
out.append("};")
out += ["", "#endif", ""]
print("\n".join(out))
